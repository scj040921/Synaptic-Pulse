CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(40) NOT NULL,
  bio VARCHAR(300) NOT NULL DEFAULT '',
  campus VARCHAR(80) NOT NULL DEFAULT '广州大学',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_url VARCHAR(300);
CREATE TABLE IF NOT EXISTS image_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uploader_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  image_url VARCHAR(300) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS user_interests (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  interest VARCHAR(30) NOT NULL,
  PRIMARY KEY (user_id, interest)
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id BIGINT NOT NULL REFERENCES users(id),
  content VARCHAR(2000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS posts_created_idx ON posts(created_at DESC);
ALTER TABLE posts ADD COLUMN IF NOT EXISTS topics VARCHAR(300) NOT NULL DEFAULT '';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS location_name VARCHAR(80) NOT NULL DEFAULT '';
ALTER TABLE posts ADD COLUMN IF NOT EXISTS latitude DOUBLE;
ALTER TABLE posts ADD COLUMN IF NOT EXISTS longitude DOUBLE;
CREATE INDEX IF NOT EXISTS posts_position_idx ON posts(latitude, longitude);
CREATE TABLE IF NOT EXISTS post_likes (
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY(post_id, user_id)
);
CREATE TABLE IF NOT EXISTS post_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT REFERENCES posts(id) ON DELETE CASCADE,
  uploader_id BIGINT NOT NULL REFERENCES users(id),
  image_url VARCHAR(300) NOT NULL UNIQUE,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO image_assets(uploader_id, image_url)
SELECT p.uploader_id, p.image_url FROM post_images p
WHERE NOT EXISTS (SELECT 1 FROM image_assets a WHERE a.image_url = p.image_url);
CREATE INDEX IF NOT EXISTS post_images_post_idx ON post_images(post_id, sort_order);
CREATE TABLE IF NOT EXISTS post_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id),
  content VARCHAR(500) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS post_comments_post_idx ON post_comments(post_id, id);
CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id BIGINT NOT NULL REFERENCES users(id),
  receiver_id BIGINT NOT NULL REFERENCES users(id),
  content VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE messages ADD COLUMN IF NOT EXISTS type VARCHAR(12) NOT NULL DEFAULT 'text';
ALTER TABLE messages ADD COLUMN IF NOT EXISTS image_url VARCHAR(300);
ALTER TABLE messages ADD COLUMN IF NOT EXISTS client_key VARCHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS messages_client_key_idx ON messages(sender_id, client_key);
CREATE INDEX IF NOT EXISTS messages_sender_idx ON messages(sender_id, receiver_id, id);
CREATE INDEX IF NOT EXISTS messages_receiver_idx ON messages(receiver_id, sender_id, id);
CREATE TABLE IF NOT EXISTS chat_reads (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  peer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  last_read_id BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY(user_id, peer_id)
);
CREATE TABLE IF NOT EXISTS training_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  practice_key VARCHAR(64) NOT NULL,
  level_name VARCHAR(12) NOT NULL,
  scenario VARCHAR(60) NOT NULL,
  source VARCHAR(12) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id, practice_key)
);
CREATE TABLE IF NOT EXISTS campus_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  host_id BIGINT NOT NULL REFERENCES users(id),
  title VARCHAR(80) NOT NULL,
  content VARCHAR(2000) NOT NULL,
  location_name VARCHAR(80) NOT NULL,
  starts_at TIMESTAMP NOT NULL,
  capacity INT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS event_signups (
  event_id BIGINT NOT NULL REFERENCES campus_events(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY(event_id, user_id)
);
CREATE TABLE IF NOT EXISTS blocks (
  blocker_id BIGINT NOT NULL REFERENCES users(id),
  blocked_id BIGINT NOT NULL REFERENCES users(id),
  PRIMARY KEY (blocker_id, blocked_id)
);
CREATE TABLE IF NOT EXISTS campus_places (
  id VARCHAR(40) PRIMARY KEY,
  campus VARCHAR(80) NOT NULL,
  name VARCHAR(100) NOT NULL,
  category VARCHAR(20) NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  description VARCHAR(500) NOT NULL,
  source_url VARCHAR(300) NOT NULL
);
CREATE TABLE IF NOT EXISTS place_favorites (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  place_id VARCHAR(40) NOT NULL REFERENCES campus_places(id) ON DELETE CASCADE,
  PRIMARY KEY(user_id, place_id)
);
ALTER TABLE campus_events ADD COLUMN IF NOT EXISTS place_id VARCHAR(40) REFERENCES campus_places(id);

